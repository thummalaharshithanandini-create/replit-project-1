export function normalizeIngredient(value) {
  const normalized = value.trim().toLocaleLowerCase();
  if (!normalized) return "";
  for (const [key, item] of Object.entries(INGREDIENT_LABELS)) {
    if (item.aliases.some((alias) => alias.toLocaleLowerCase() === normalized)) return key;
  }
  return normalized;
}

export function ingredientName(value, language) {
  const item = INGREDIENT_LABELS[value];
  return item ? item[language] : value;
}
